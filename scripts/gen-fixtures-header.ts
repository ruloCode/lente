// Writes firmware/selftest/fixtures.h from test/fixtures/frames.json, so the firmware
// self-test checks its encoder against the same golden frames the hub tests decode.
//
// Usage: pnpm gen:fixtures   (a unit test fails when the committed header is stale)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

interface Fixture {
  name: string;
  type: string;
  base64: string;
  seq?: number;
  timeMs?: number;
  samples?: number[];
}

const FIXTURES = new URL("../test/fixtures/frames.json", import.meta.url);
export const HEADER = new URL("../firmware/selftest/fixtures.h", import.meta.url);

const ident = (name: string) => name.toUpperCase().replace(/[^A-Z0-9]/g, "_");
const hex = (bytes: Buffer) =>
  Array.from(bytes, (b, i) => (i % 12 === 0 ? "\n  " : " ") + "0x" + b.toString(16).padStart(2, "0") + ",").join("");

export function renderFixturesHeader(frames: Fixture[]): string {
  const out = [
    "// GENERATED by scripts/gen-fixtures-header.ts from test/fixtures/frames.json. Do not edit.",
    "// Full wire frames (type, u32 LE length, payload) of protocol v2.",
    "#pragma once",
    "#include <stdint.h>",
    "",
  ];
  for (const f of frames) {
    const id = ident(f.name);
    const wire = Buffer.from(f.base64, "base64");
    out.push(`static const uint8_t FIXTURE_${id}[] = {${hex(wire)}\n};`);
    if (f.type === "A") {
      out.push(`#define FIXTURE_${id}_SEQ ${f.seq}u`, `#define FIXTURE_${id}_MS ${f.timeMs}u`);
      out.push(`static const int16_t FIXTURE_${id}_SAMPLES[] = {${f.samples!.join(", ")}};`);
    }
    out.push("");
  }
  return out.join("\n");
}

export function loadFixtures(): Fixture[] {
  return (JSON.parse(readFileSync(FIXTURES, "utf8")) as { frames: Fixture[] }).frames;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(HEADER, renderFixturesHeader(loadFixtures()));
  console.log(`wrote ${fileURLToPath(HEADER)}`);
}
