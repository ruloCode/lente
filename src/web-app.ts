/** Where the browser goes after Google: `/app` or a path under it, made of safe characters; anything else is refused. */
export function safeNext(next: string | null | undefined): string | undefined {
  if (!next || next.length > 200) return undefined;
  if (!/^\/app(\/[A-Za-z0-9_~-]+)*\/?$/.test(next)) return undefined;
  return next;
}

/** The cookie that carries the return path to the callback (only on /auth, 10 minutes). */
export const NEXT_COOKIE = "lente_next";

/** What `GET /app/session` answers: the hub's sign-in mode and whether this browser may use the app. */
export function appSession(mode: "open" | "pairing" | "accounts", who: { email?: string } | undefined): { mode: string; signedIn: boolean; email: string | null } {
  return { mode, signedIn: mode === "open" || Boolean(who), email: who?.email ?? null };
}
