// The desktop web app (add-web-desktop), served at /app. Its modules live in web/app/ and go out as
// they are; this file decides which path is which file, builds the shell and the theme sheet, and
// turns the hub's tested page scripts (the /desktop capture pipeline, the transcript reducer, the
// mark) into modules, so the browser runs the very code the tests cover. Pure apart from reading
// the folder's file list once.

import { readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { logoSvg } from "./brand.ts";
import { DESKTOP_CAPTURE_PAGE_SCRIPT } from "./desktop-capture.ts";
import { PHONE_AUDIO_PAGE_SCRIPT } from "./phone-audio.ts";
import { THEME_TOKENS } from "./theme.ts";
import { TRANSCRIPT_PAGE_SCRIPT } from "./transcript-view.ts";

/** Where the app lives on the hub. */
export const APP_PREFIX = "/app";
/** What a static file of the app may be. */
const STATIC_EXT = /\.(js|css|svg)$/;
const SAFE_PATH = /^[a-z0-9][a-z0-9_.-]*(\/[a-z0-9][a-z0-9_.-]*)*$/i;

export const CONTENT_TYPES: Record<string, string> = {
  js: "text/javascript; charset=utf-8",
  css: "text/css; charset=utf-8",
  svg: "image/svg+xml",
  json: "application/json",
};

/**
 * The app's Content-Security-Policy: scripts and styles only from the hub, images also from data
 * and blob URLs (photos arrive as data URLs), the stream and the device socket to the same origin.
 */
export const APP_CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "media-src 'self' blob: mediastream:",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
].join("; ");

export const isAppPath = (path: string | undefined): boolean => path === APP_PREFIX || Boolean(path?.startsWith(`${APP_PREFIX}/`));

/** What a path under /app is: a file in the folder, a file the hub builds, the session, the shell, or nothing. */
export type AppAsset = { kind: "file"; name: string } | { kind: "generated"; name: GeneratedName } | { kind: "session" } | { kind: "shell" } | { kind: "missing" };

export const GENERATED = ["theme.css", "lib/capture-pipeline.js", "lib/transcript-view.js", "lib/brand.js"] as const;
export type GeneratedName = (typeof GENERATED)[number];

/**
 * Resolves `/app/<rest>` (no query string). Only names in `files` (relative to web/app/, `/`
 * separated) are served from disk; a path that looks like a file but is unknown is missing, and
 * any other path is a client route that gets the shell.
 */
export function resolveAppPath(path: string, files: ReadonlySet<string>): AppAsset {
  if (!isAppPath(path)) return { kind: "missing" };
  const rest = path.slice(APP_PREFIX.length + 1);
  if (rest === "session") return { kind: "session" };
  if ((GENERATED as readonly string[]).includes(rest)) return { kind: "generated", name: rest as GeneratedName };
  const looksLikeFile = /\.[a-z0-9]+$/i.test(rest);
  if (!looksLikeFile) return rest === "" || SAFE_PATH.test(rest.replace(/\/+$/, "")) ? { kind: "shell" } : { kind: "missing" };
  if (!STATIC_EXT.test(rest) || !SAFE_PATH.test(rest) || rest.includes("..") || !files.has(rest)) return { kind: "missing" };
  return { kind: "file", name: rest };
}

/** Every file under `dir`, relative and `/` separated, read once when the hub starts. */
export function listAppFiles(dir: string): Set<string> {
  const out = new Set<string>();
  const walk = (at: string): void => {
    let names: string[];
    try {
      names = readdirSync(at);
    } catch {
      return;
    }
    for (const name of names) {
      const full = join(at, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (STATIC_EXT.test(name)) out.add(relative(dir, full).split(sep).join("/"));
    }
  };
  walk(dir);
  return out;
}

/** Content type for a served name. */
export const contentType = (name: string): string => CONTENT_TYPES[name.split(".").pop() ?? ""] ?? "application/octet-stream";

/** The light and the dark custom properties of the shared theme, as written in `THEME_TOKENS`. */
export function themeBlocks(tokens = THEME_TOKENS): { light: string; dark: string } {
  const blocks = [...tokens.matchAll(/:root \{([^}]*)\}/g)].map((m) => m[1]!.trim());
  if (blocks.length < 2) throw new Error("THEME_TOKENS no longer has a light and a dark :root block");
  return { light: blocks[0]!, dark: blocks[1]! };
}

/**
 * The theme for the app: the shared tokens (light, dark from the system), and the same values under
 * `data-theme` so the user's choice wins over the system's.
 */
export function appThemeCss(tokens = THEME_TOKENS): string {
  const { light, dark } = themeBlocks(tokens);
  return `/* Generated by src/web-app.ts from src/theme.ts: do not edit. */\n${tokens}\n  :root[data-theme="light"] { ${light} color-scheme: light; }\n  :root[data-theme="dark"] { ${dark} color-scheme: dark; }\n`;
}

/** Page scripts of the hub as modules: the code and an export of the names the app uses. */
export function generatedModule(name: GeneratedName): string {
  const header = "// Generated by src/web-app.ts from the hub's tested modules: do not edit.\n";
  switch (name) {
    case "theme.css":
      return appThemeCss();
    case "lib/capture-pipeline.js":
      return `${header}${PHONE_AUDIO_PAGE_SCRIPT}\n${DESKTOP_CAPTURE_PAGE_SCRIPT}\nexport { PcmResampler, PcmFramer, uplinkFrame, phoneHello, phoneAudioFrame, SceneDetector, toLuma, SCENE_THUMB_WIDTH, SCENE_THUMB_HEIGHT };\n`;
    case "lib/transcript-view.js":
      return `${header}${TRANSCRIPT_PAGE_SCRIPT}\nexport { emptyTranscript, reduceTranscript };\n`;
    case "lib/brand.js":
      // The mark without inline style (the CSP allows none): the line takes the accent from app.css.
      return `${header}export const MARK_SVG = ${JSON.stringify(logoSvg(false).replace(/ style="[^"]*"/, ' class="mark-line"').replace("<svg ", '<svg aria-hidden="true" focusable="false" '))};\n`;
  }
}

